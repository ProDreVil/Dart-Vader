def get_word_score(word):
    return LEXICON.get(word.lower(), 0)

def is_negation(word):
    return word.lower() in NEGATIONS

def get_booster(word):
    return BOOSTERS.get(word.lower(), 0)


def levenshtein_distance(first, second):
    first = first.lower()
    second = second.lower()
    rows = len(first) + 1
    columns = len(second) + 1
    distance = [[0] * columns for _ in range(rows)]
    for i in range(rows):
        distance[i][0] = i
    for j in range(columns):
        distance[0][j] = j
    for i in range(1, rows):
        for j in range(1, columns):
            cost = 0 if first[i - 1] == second[j - 1] else 1
            distance[i][j] = min(distance[i - 1][j] + 1, distance[i][j - 1] + 1, distance[i - 1][j - 1] + cost)
            if (i > 1 and j > 1 and first[i - 1] == second[j - 2] and first[i - 2] == second[j - 1]):
                distance[i][j] = min(distance[i][j], distance[i - 2][j - 2] + 1)
    return distance[-1][-1]

def find_closest_word(word):
    word = word.lower()
    best_match = None
    best_distance = float("inf")
    for lexicon_word in LEXICON:
        distance = levenshtein_distance(word, lexicon_word)
        if distance < best_distance:
            best_distance = distance
            best_match = lexicon_word
    max_distance = max(1, len(word) // 4)
    if best_distance <= max_distance:
        return best_match, best_distance
    return None, best_distance